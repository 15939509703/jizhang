-- Free follow-up features: reimbursement, savings, reports, backup, family sharing and subscriptions.

CREATE TABLE `fin_reimbursement` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `reimbursement_no` VARCHAR(40) NOT NULL,
  `book_id` BIGINT UNSIGNED NOT NULL,
  `expense_transaction_id` BIGINT UNSIGNED NOT NULL,
  `reimbursement_transaction_id` BIGINT UNSIGNED DEFAULT NULL,
  `expected_amount` DECIMAL(19,2) NOT NULL,
  `reimburser_name` VARCHAR(128) DEFAULT NULL,
  `submitted_date` DATE DEFAULT NULL,
  `expected_date` DATE DEFAULT NULL,
  `reimbursed_time` DATETIME(3) DEFAULT NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  `note` VARCHAR(1000) DEFAULT NULL,
  `version` INT UNSIGNED NOT NULL DEFAULT 0,
  `creator` VARCHAR(64) NOT NULL DEFAULT 'system',
  `created_time` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `modifier` VARCHAR(64) NOT NULL DEFAULT 'system',
  `modified_time` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_reimbursement_no` (`reimbursement_no`),
  UNIQUE KEY `uk_reimbursement_expense` (`expense_transaction_id`),
  UNIQUE KEY `uk_reimbursement_income` (`reimbursement_transaction_id`),
  KEY `idx_reimbursement_book_status` (`book_id`, `status`, `submitted_date`),
  CONSTRAINT `fk_reimbursement_book` FOREIGN KEY (`book_id`) REFERENCES `fin_book` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_reimbursement_expense` FOREIGN KEY (`expense_transaction_id`) REFERENCES `fin_transaction` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_reimbursement_income` FOREIGN KEY (`reimbursement_transaction_id`) REFERENCES `fin_transaction` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `ck_reimbursement_amount` CHECK (`expected_amount` > 0)
) ENGINE=InnoDB COMMENT='报销项目';

CREATE TABLE `fin_savings_goal` (
