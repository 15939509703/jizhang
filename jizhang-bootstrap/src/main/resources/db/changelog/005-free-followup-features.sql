  `book_id` BIGINT UNSIGNED NOT NULL,
  `name` VARCHAR(128) NOT NULL,
  `description` VARCHAR(1000) DEFAULT NULL,
  `target_amount` DECIMAL(19,2) NOT NULL,
  `initial_amount` DECIMAL(19,2) NOT NULL DEFAULT 0,
  `target_account_id` BIGINT UNSIGNED DEFAULT NULL,
  `start_date` DATE NOT NULL,
  `target_date` DATE DEFAULT NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
  `version` INT UNSIGNED NOT NULL DEFAULT 0,
  `deleted_flag` TINYINT NOT NULL DEFAULT 0,
  `creator` VARCHAR(64) NOT NULL DEFAULT 'system',
  `created_time` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `modifier` VARCHAR(64) NOT NULL DEFAULT 'system',
  `modified_time` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
